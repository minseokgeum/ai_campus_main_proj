// 예상 가격을 실제로 거래될 수 있는 가격(한국거래소 호가 단위, 2023-01~)으로 맞춘 뒤 금액을 센다(2026-11-26 사용자 결정 '상식적인 쪽으로').
// 예상 가격 = 어제 종가 × (1 + 예상 %)는 1,050,999.7원처럼 실제로 없는 가격이 나와, 화면마다 금액이 몇 원씩 달랐다.
// 이제 홈 · 한 화면에 보기 · 밤사이 목록·계좌 · 종목 창 · 노란 띠 양 끝 · 종목 상세 예측 창 · 밤사이 계산기가 모두 이 규칙으로 센다(화면의 예상 %는 그대로).

/** 호가 단위로 맞춘 가격 */
export function tick(p: number): number {
  const u = p < 2000 ? 1 : p < 5000 ? 5 : p < 20000 ? 10 : p < 50000 ? 50 : p < 200000 ? 100 : p < 500000 ? 500 : 1000;
  return Math.round(p / u) * u;
}

/** 예상 %(어제 종가 대비 비율 r)로 그 가격에 시작했을 때 수량 q의 금액 변화 */
export const expAmt = (q: number, pc: number, r: number) => q * (tick(pc * (1 + r)) - pc);
